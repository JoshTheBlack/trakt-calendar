"""Tier boards: the data layer behind ranking titles into ordered tiers.

One job: read and write `tier_boards`, `tier_categories` and `tier_items`. No
HTTP, no request objects, no image work — routes parse and respond, this module
decides what the database ends up holding.

THE ACCESS RULE, and the reason this module reads the way it does: a board or a
category is NEVER addressed by its integer id from outside. Every public
function here takes a `user_id` from the session plus a client-supplied `uid`,
and resolves the pair against rows the session user owns. Integer ids exist only
inside a single call, after ownership has been established. That is what makes a
cross-tenant reference impossible to even express: there is no request shape that
names somebody else's board, because the only name a request can use is scoped to
the caller. Every UPDATE and DELETE additionally carries the ownership predicate
in its WHERE clause, so a mistake in the resolution step still cannot write
across accounts.

ITEM ADDRESSING. Items have no uid column of their own. Their identity within a
board is the triple (media, match_source, match_id), which is also their UNIQUE
constraint, so the composite key "{media}:{match_source}:{match_id}" is what a
client refers to an item by. Like a uid it survives a restore into a database
whose rowids came out different, and like a uid it is meaningless outside the
board it was resolved against.

WHAT A SAVE MAY DO. save_layout() is targeted upserts and updates inside one
transaction, never a wipe-and-reinsert: reinserting loses whatever a second tab
wrote in between and churns the id space for no reason. A stale writer is caught
by the board's `version`, which the client echoes back and which is bumped on
every accepted write.
"""
from __future__ import annotations

import json
import re
from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any

from . import db

# Caps. Every one of these is enforced by rejecting the whole request, never by
# quietly truncating: a user who pasted a 90-character board name should be told
# it is too long, not shown a name they did not choose.
MAX_BOARD_NAME = 60
MAX_CATEGORY_LABEL = 40
MAX_RANK_PRIORITY = 1000
MAX_BOARDS_PER_USER = 50
MAX_BOARDS_PER_YEAR = 20
MAX_CATEGORIES_PER_BOARD = 30
# Far above the 100-item export ceiling on purpose: a board is a working set to
# curate down from, not just the finished list. This is also the number the
# pool's pagination and the poster warming are sized against.
MAX_ITEMS_PER_BOARD = 1000
MAX_UID_LENGTH = 64

MEDIA_VALUES = frozenset({"show", "movie"})
MEDIA_SCOPES = frozenset({"show", "movie", "mixed"})
# The identity waterfall, in preference order. A row's match_source is whichever
# of these was the first shared id available when the title was resolved.
MATCH_SOURCES = ("tmdb", "tvdb", "imdb", "mal")
ADDED_FROM_VALUES = frozenset({"manual", "tracker", "ratings"})

_COLOUR = re.compile(r"^#[0-9A-Fa-f]{6}$")
# A uid is generated by the client and then used as a database key and an HTML
# id, so it is held to an unambiguous alphabet rather than trusted.
_UID = re.compile(r"^[A-Za-z0-9_-]{1,%d}$" % MAX_UID_LENGTH)

# The columns a board row exposes outside this module, in the order the UI reads
# them. Listed once so fetch_boards and fetch_board cannot drift apart.
_BOARD_FIELDS = ("uid", "name", "year", "media_scope", "sort_order",
                 "created_at", "updated_at", "version")


class RankerError(Exception):
    """Base for the refusals this module raises. Each subclass maps to one HTTP
    status in the route layer, which is the only place that knows about HTTP."""


class BoardNotFound(RankerError):
    """No board with that uid belongs to this user.

    Deliberately the same answer for "no such board" and "somebody else's
    board": a caller who can tell those apart can enumerate other people's
    boards by uid, which is exactly the disclosure the uid addressing exists to
    prevent.
    """


class ValidationError(RankerError):
    """A payload broke a cap or a format rule. Nothing was written."""


class VersionConflict(RankerError):
    """The board changed since the client last read it — another tab saved
    first. The caller reloads rather than guessing which write wins."""


@dataclass(frozen=True)
class ItemKey:
    """An item's identity within a board: the same triple as its UNIQUE
    constraint, parsed from the composite key a client sends."""
    media: str
    match_source: str
    match_id: str

    def __str__(self) -> str:
        return f"{self.media}:{self.match_source}:{self.match_id}"


def item_key(media: str, match_source: str, match_id: str) -> str:
    """The string a client uses to name one item on a board."""
    return str(ItemKey(media, match_source, match_id))


def parse_item_key(value: Any) -> ItemKey:
    """Parse a composite item key, raising rather than returning a sentinel a
    caller could forget to check.

    Split at most twice, because an imdb or mal id is opaque to us and may one
    day contain the separator; media and match_source never can, since both come
    from closed sets checked here.
    """
    if not isinstance(value, str):
        raise ValidationError("Item keys must be strings.")
    parts = value.split(":", 2)
    if len(parts) != 3:
        raise ValidationError(f"Malformed item key: {value!r}.")
    media, match_source, match_id = parts
    if media not in MEDIA_VALUES:
        raise ValidationError(f"Unknown media type {media!r}.")
    if match_source not in MATCH_SOURCES:
        raise ValidationError(f"Unknown match source {match_source!r}.")
    if not match_id:
        raise ValidationError("An item key needs a match id.")
    return ItemKey(media, match_source, match_id)


