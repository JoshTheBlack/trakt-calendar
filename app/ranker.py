async def delete_category(user_id: int, board_uid: str, category_uid: str) -> int:
    """Delete one tier. Its titles fall back to the board's pool rather than
    being deleted with it — losing a curated list to a mis-click is not an
    acceptable outcome, and it is what makes undo trivial.

    Returns how many titles returned to the pool. The fallback itself is the
    schema's ON DELETE SET NULL; this counts them first so the caller can say so.
    """
    def _work(conn: db.Connection) -> int:
        board = _resolve_board(conn, user_id, board_uid)
        board_id = int(board["id"])
        categories = _category_ids(conn, board_id)
        category_id = categories.get(_uid(category_uid, "category"))
        if category_id is None:
            raise ValidationError(f"No tier {category_uid!r} on this board.")
        returned = int(conn.execute(
            "SELECT COUNT(*) FROM tier_items WHERE category_id = ? AND board_id = ?",
            (category_id, board_id),
        ).fetchone()[0])
        conn.execute(
            "DELETE FROM tier_categories WHERE id = ? AND board_id = ?",
            (category_id, board_id),
        )
        _touch(conn, board_id, user_id, db.now())
        return returned

    return await db.transaction(_work)


async def save_layout(user_id: int, board_uid: str, payload: Mapping[str, Any]) -> dict[str, Any]:
    """Write a whole arrangement — tiers, their order, and which titles sit
    where — in one transaction, and return the board's new version.

    The payload is:
        {"version": int,
         "categories": [{"uid", "label", "rank_priority", "is_isolated",
                         "colour", "items": [item key, ...]}, ...],
         "pool": [item key, ...]}

    Rules that make this safe to call from two tabs:
      - `version` must match the stored one or nothing is written (VersionConflict).
      - Every category uid currently on the board must appear in `categories`;
        a uid that does not exist yet creates a tier. A client holding the
        matching version by definition knows the full set, so a missing one means
        the payload was assembled from something other than a current read.
      - Every item key must resolve to a title on THIS board. One that does not
        rejects the whole payload rather than writing the part we understood.
      - Titles named nowhere in the payload are left exactly where they are, so
        a save cannot silently empty a tier it never mentioned.
      - sort_order and rank_in_category are assigned by position here and never
        taken from the client, so the stored ordering is always a dense 0..N-1.
    """
    if not isinstance(payload, Mapping):
        raise ValidationError("Expected a layout object.")
    version = payload.get("version")
    if not isinstance(version, int) or isinstance(version, bool) or version < 0:
        raise ValidationError("A layout save must carry the board version it was built from.")
    categories = payload.get("categories") or []
    if not isinstance(categories, list):
        raise ValidationError("`categories` must be a list.")
    if len(categories) > MAX_CATEGORIES_PER_BOARD:
        raise ValidationError(f"A board holds at most {MAX_CATEGORIES_PER_BOARD} tiers.")
    pool = payload.get("pool") or []
    if not isinstance(pool, list):
        raise ValidationError("`pool` must be a list.")

    wanted = [_normalize_category(entry) for entry in categories]
    if len({entry["uid"] for entry in wanted}) != len(wanted):
        raise ValidationError("Two tiers cannot share an id.")
    pool_keys = [parse_item_key(key) for key in pool]
    ts = db.now()

    def _work(conn: db.Connection) -> dict[str, Any]:
        board = _resolve_board(conn, user_id, board_uid)
        board_id = int(board["id"])
        if int(board["version"]) != version:
            raise VersionConflict(
                "This board changed in another tab. Reload it and try again."
            )

        existing = _category_ids(conn, board_id)
        supplied = {entry["uid"] for entry in wanted}
        if missing := set(existing) - supplied:
            raise ValidationError(
                f"The layout is missing {len(missing)} tier(s) that are on this board."
            )

        known_items = _item_ids(conn, board_id)
        # Resolved for the WHOLE payload before a single write, so an unknown key
        # in the last tier refuses the first tier too.
        placements: list[tuple[int, str, int]] = []
        seen: set[str] = set()
        for entry in wanted:
            for rank, key in enumerate(entry["items"]):
                name = str(key)
                if name not in known_items:
                    raise ValidationError(f"No title {name!r} on this board.")
                if name in seen:
                    raise ValidationError(f"{name!r} appears twice in this layout.")
                seen.add(name)
                placements.append((known_items[name], entry["uid"], rank))
        for key in pool_keys:
            name = str(key)
            if name not in known_items:
                raise ValidationError(f"No title {name!r} on this board.")
            if name in seen:
                raise ValidationError(f"{name!r} appears twice in this layout.")
            seen.add(name)

        category_ids = dict(existing)
        for order, entry in enumerate(wanted):
            category_id = existing.get(entry["uid"])
            if category_id is None:
                cur = conn.execute(
                    "INSERT INTO tier_categories (board_id, uid, label, rank_priority, "
                    "is_isolated, sort_order, colour, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                    (board_id, entry["uid"], entry["label"], entry["rank_priority"],
                     int(entry["is_isolated"]), order, entry["colour"], ts),
                )
                category_ids[entry["uid"]] = int(cur.lastrowid)
            else:
                conn.execute(
                    "UPDATE tier_categories SET label = ?, rank_priority = ?, is_isolated = ?, "
                    "sort_order = ?, colour = ? WHERE id = ? AND board_id = ?",
                    (entry["label"], entry["rank_priority"], int(entry["is_isolated"]),
                     order, entry["colour"], category_id, board_id),
                )

        for item_id, category_uid, rank in placements:
            conn.execute(
                "UPDATE tier_items SET category_id = ?, rank_in_category = ? "
                " WHERE id = ? AND board_id = ?",
                (category_ids[category_uid], rank, item_id, board_id),
            )
        for key in pool_keys:
            conn.execute(
                "UPDATE tier_items SET category_id = NULL, rank_in_category = 0 "
                " WHERE id = ? AND board_id = ?",
                (known_items[str(key)], board_id),
            )

        new_version = _touch(conn, board_id, user_id, ts)
        return {"version": new_version}

    return await db.transaction(_work)


def _normalize_category(entry: Any) -> dict[str, Any]:
    if not isinstance(entry, Mapping):
        raise ValidationError("Each tier must be an object.")
    items = entry.get("items") or []
    if not isinstance(items, list):
        raise ValidationError("A tier's `items` must be a list.")
    return {
        "uid": _uid(entry.get("uid"), "tier"),
        "label": _name(entry.get("label"), MAX_CATEGORY_LABEL, "tier label"),
        "rank_priority": _rank_priority(entry.get("rank_priority", 0)),
        "is_isolated": bool(entry.get("is_isolated")),
        "colour": _colour(entry.get("colour")),
        "items": [parse_item_key(key) for key in items],
    }


# ---------------------------------------------------------------------------
# the tier template and the ratings seed
# ---------------------------------------------------------------------------
# One S/A/B/C/D/F set, defined once. The seed creates whichever of these it
# needs, and the UI's "apply template" offers the same six — two spellings of
# the same ladder would put a board in a state where a re-seed created
# duplicates of tiers the user already had.
#
# The uids are FIXED rather than generated, which is what makes "create the ones
# that are missing" work: a second seed finds the tier it made the first time
# instead of adding another beside it. Priorities descend in tens so a user can
# slot something between two of them without renumbering.
TIER_TEMPLATE: tuple[dict[str, Any], ...] = (
    {"uid": "tier-s", "label": "S", "rank_priority": 60, "colour": "#FF7F7F"},
    {"uid": "tier-a", "label": "A", "rank_priority": 50, "colour": "#FFBF7F"},
    {"uid": "tier-b", "label": "B", "rank_priority": 40, "colour": "#FFDF7F"},
    {"uid": "tier-c", "label": "C", "rank_priority": 30, "colour": "#BFEF7F"},
    {"uid": "tier-d", "label": "D", "rank_priority": 20, "colour": "#7FC7FF"},
    {"uid": "tier-f", "label": "F", "rank_priority": 10, "colour": "#B0B4BA"},
)
_TEMPLATE_BY_UID = {entry["uid"]: entry for entry in TIER_TEMPLATE}

# A 1-10 score onto that ladder. The top three scores each get their own tier
# because that is where a person's opinion is most differentiated; everything at
# 5 or below lands together, because "I did not like it" is one verdict however
# it was spelled.
_TIER_FOR_RATING = {10: "tier-s", 9: "tier-a", 8: "tier-b", 7: "tier-c", 6: "tier-d"}
_LOWEST_TIER = "tier-f"


def tier_for_rating(rating: int) -> str:
    """Which template tier a score seeds into."""
    return _TIER_FOR_RATING.get(int(rating), _LOWEST_TIER)


async def seed_ratings(
    user_id: int, board_uid: str, entries: list[Mapping[str, Any]], *, commit: bool = False,
) -> dict[str, Any]:
    """Arrange rated titles into the template tiers, or report what that would
    do when `commit` is false.

    A SEED, NOT A SYNC, and the difference is the whole design:
      - A title the user has already placed is never moved. Their arrangement is
        the artifact; the scores are only a starting point.
      - Titles the board does not hold yet are added with their score, then
        placed. A title that arrives with a rating and no tier would leave the
        user to do by hand the exact work they asked for.
      - Nothing here runs on a schedule or repeats itself. Seeding a board twice
        does nothing the second time beyond whatever was rated in between.

    Titles outside the board's media scope are skipped rather than refused: a
    movies board seeded from a mixed ratings list should get the movies, not an
    error about the shows.

    `entries` carry the tier_items fields plus `user_rating`. Returns the counts
    a preview shows, and — when committed — the board's new version.
    """
    rated = [(_normalize_ref(entry), _rating(entry.get("user_rating"))) for entry in entries]

    def _work(conn: db.Connection) -> dict[str, Any]:
        board = _resolve_board(conn, user_id, board_uid)
        board_id = int(board["id"])
        scope = board["media_scope"]
        in_scope = [(row, score) for row, score in rated
                    if scope == "mixed" or row["media"] == scope]

        placements = _item_placements(conn, board_id)
        categories = _category_ids(conn, board_id)
        # Highest score first so the tiers fill in the order somebody would have
        # dragged them, and so a truncated run keeps the titles that matter most.
        ordered = sorted(in_scope, key=lambda pair: (-pair[1], pair[0]["title"]))

        new_items: list[tuple[dict[str, Any], int, str]] = []   # row, score, tier uid
        moves: list[tuple[int, str]] = []                       # item id, tier uid
        already_placed = 0
        seen: set[str] = set()
        for row, score in ordered:
            key = item_key(row["media"], row["match_source"], row["match_id"])
            if key in seen:
                # The same title twice in one payload — a show rated under two
                # ids, say. The first (highest) score has already claimed it, and
                # counting the second would report an insert the UNIQUE will drop.
                continue
            seen.add(key)
            tier_uid = tier_for_rating(score)
            existing = placements.get(key)
            if existing is None:
                new_items.append((row, score, tier_uid))
            elif existing[1] is not None:
                already_placed += 1
            else:
                moves.append((existing[0], tier_uid))

        wanted_tiers = {uid for _, _, uid in new_items} | {uid for _, uid in moves}
        missing = [uid for entry in TIER_TEMPLATE
                   if (uid := entry["uid"]) in wanted_tiers and uid not in categories]
        if len(categories) + len(missing) > MAX_CATEGORIES_PER_BOARD:
            raise ValidationError(f"A board holds at most {MAX_CATEGORIES_PER_BOARD} tiers.")
        held = int(conn.execute(
            "SELECT COUNT(*) FROM tier_items WHERE board_id = ?", (board_id,)
        ).fetchone()[0])
        if held + len(new_items) > MAX_ITEMS_PER_BOARD:
            raise ValidationError(f"A board holds at most {MAX_ITEMS_PER_BOARD} titles.")

        summary = {
            "tiers_created": len(missing),
            "titles_added": len(new_items),
            "titles_placed": len(new_items) + len(moves),
            "already_placed": already_placed,
            "out_of_scope": len(rated) - len(in_scope),
            "version": int(board["version"]),
        }
        if not commit:
            return summary

        ts = db.now()
        next_order = int(conn.execute(
            "SELECT COALESCE(MAX(sort_order), -1) + 1 FROM tier_categories WHERE board_id = ?",
            (board_id,),
        ).fetchone()[0])
        for offset, uid in enumerate(missing):
            template = _TEMPLATE_BY_UID[uid]
            cur = conn.execute(
                "INSERT INTO tier_categories (board_id, uid, label, rank_priority, is_isolated, "
                "sort_order, colour, created_at) VALUES (?, ?, ?, ?, 0, ?, ?, ?)",
                (board_id, uid, template["label"], template["rank_priority"],
                 next_order + offset, template["colour"], ts),
            )
            categories[uid] = int(cur.lastrowid)

        # Appended AFTER whatever each tier already holds, so a seed onto a board
        # somebody has started arranging never reshuffles their existing order.
        ranks = _next_ranks(conn, board_id, categories.values())
        for row, score, uid in new_items:
            category_id = categories[uid]
            _insert_item(conn, board_id, row, "ratings", ts,
                         category_id=category_id, rank=ranks[category_id])
            ranks[category_id] += 1
        for item_id, uid in moves:
            category_id = categories[uid]
            conn.execute(
                "UPDATE tier_items SET category_id = ?, rank_in_category = ? "
                " WHERE id = ? AND board_id = ?",
                (category_id, ranks[category_id], item_id, board_id),
            )
            ranks[category_id] += 1

        summary["version"] = _touch(conn, board_id, user_id, ts)
        return summary

    return await (db.transaction(_work) if commit else db.run(_work))


def _rating(value: Any) -> int:
    score = _optional_int(value)
    if score is None or not 1 <= score <= 10:
        raise ValidationError("A rating must be a whole number from 1 to 10.")
    return score


def _item_placements(conn: db.Connection, board_id: int) -> dict[str, tuple[int, int | None]]:
    """Composite item key -> (id, category_id), for one already-owned board. The
    category is what tells an unplaced title apart from one the user has already
    put somewhere."""
    return {
        item_key(row["media"], row["match_source"], row["match_id"]):
            (int(row["id"]), row["category_id"])
        for row in conn.execute(
            "SELECT id, category_id, media, match_source, match_id FROM tier_items "
            " WHERE board_id = ?", (board_id,),
        )
    }


def _next_ranks(conn: db.Connection, board_id: int, category_ids) -> dict[int, int]:
    """The rank an appended title takes in each tier: one past whatever is
    already there. Read once for the whole seed rather than per title."""
    ranks = {int(cid): 0 for cid in category_ids}
    for row in conn.execute(
        "SELECT category_id, MAX(rank_in_category) + 1 AS next FROM tier_items "
        " WHERE board_id = ? AND category_id IS NOT NULL GROUP BY category_id",
        (board_id,),
    ):
        ranks[int(row["category_id"])] = int(row["next"])
    return ranks


# ---------------------------------------------------------------------------
# backup and restore
# ---------------------------------------------------------------------------
# EVERYTHING IS KEYED BY uid, NEVER BY INTEGER id. A backup's whole purpose is to
# be restorable somewhere else — a rebuilt database, a second instance, an
# account that was deleted and remade — and in any of those the autoincrement ids
# that were current when the file was written point at unrelated rows or at
# nothing at all. Boards and categories carry their uid; an item names its
# category by that uid, and items are nested inside their board so a uid only has
# to be unique where it actually is (per board).
#
# NOT IN THE DOCUMENT, deliberately: `show_posters` (shared, rebuildable, and
# nobody's personal data), and avatars and saved images (binary, large, and not
# something a JSON document should carry). The UI says so where it offers this.

# Bump only on an incompatible change to the shape below. A restore refuses a
# version it does not understand rather than guessing at the layout.
EXPORT_SCHEMA = 1
SUPPORTED_EXPORT_SCHEMAS = (1,)

# The board columns a backup carries. `version` is not among them: it counts
# saves against THIS database's copy of the board, so carrying it across would
# tell a client to expect a history the restored row does not have.
_BACKUP_BOARD_FIELDS = ("uid", "name", "year", "media_scope", "sort_order",
                        "created_at", "updated_at")
_BACKUP_CATEGORY_FIELDS = ("uid", "label", "rank_priority", "is_isolated",
                           "sort_order", "colour", "created_at")
_BACKUP_ITEM_FIELDS = ("media", "match_source", "match_id", "tmdb", "ids_json",
                       "title", "year", "network", "season_count", "episode_count",
                       "runtime", "user_rating", "added_from", "rank_in_category",
                       "created_at")


async def export_user_data(user_id: int) -> dict[str, Any]:
    """This user's every board, tier and title as one JSON-able document.

    Three queries regardless of how many boards there are — one per table,
    grouped in Python — rather than a walk that costs a query per board.
    """
    def _work(conn: db.Connection) -> dict[str, Any]:
        boards = conn.execute(
            "SELECT * FROM tier_boards WHERE user_id = ? ORDER BY sort_order, id",
            (user_id,),
        ).fetchall()
        categories: dict[int, list[dict[str, Any]]] = {}
        category_uids: dict[int, str] = {}
        for row in conn.execute(
            "SELECT c.* FROM tier_categories c JOIN tier_boards b ON b.id = c.board_id "
            " WHERE b.user_id = ? ORDER BY c.sort_order, c.id",
            (user_id,),
        ):
            categories.setdefault(int(row["board_id"]), []).append(
                {field: row[field] for field in _BACKUP_CATEGORY_FIELDS}
            )
            category_uids[int(row["id"])] = str(row["uid"])
        items: dict[int, list[dict[str, Any]]] = {}
        for row in conn.execute(
            "SELECT i.* FROM tier_items i JOIN tier_boards b ON b.id = i.board_id "
            " WHERE b.user_id = ? ORDER BY i.rank_in_category, i.id",
            (user_id,),
        ):
            entry = {field: row[field] for field in _BACKUP_ITEM_FIELDS}
            # NULL category means the board's pool, and it stays NULL through the
            # round trip: a pool title is unranked work in progress, not a title
            # whose tier went missing.
            entry["category_uid"] = (
                None if row["category_id"] is None
                else category_uids.get(int(row["category_id"]))
            )
            items.setdefault(int(row["board_id"]), []).append(entry)

        return {
            "schema": EXPORT_SCHEMA,
            "exported_at": db.now(),
            "boards": [
                {
                    **{field: row[field] for field in _BACKUP_BOARD_FIELDS},
                    "categories": categories.get(int(row["id"]), []),
                    "items": items.get(int(row["id"]), []),
                }
                for row in boards
            ],
        }

    return await db.run(_work)


async def restore_user_data(user_id: int, doc: Any) -> int:
    """Replace this user's boards with the document's, in one transaction, and
    return how many boards were written.

    REPLACE, not merge: merging would need a conflict rule for every field and
    for every arrangement, and the thing being restored is precisely an
    arrangement. The user comes from the session — a `user_id` anywhere in the
    file is ignored — so a document can never write into somebody else's account.

    The whole document is validated before a single row is deleted, so a file
    that turns out to be malformed halfway through leaves the boards that are
    already here untouched.
    """
    boards = _validate_backup(doc)
    ts = db.now()

    def _work(conn: db.Connection) -> int:
        # The cascade takes the categories and items with it.
        conn.execute("DELETE FROM tier_boards WHERE user_id = ?", (user_id,))
        for order, board in enumerate(boards):
            cur = conn.execute(
                "INSERT INTO tier_boards (user_id, uid, name, year, media_scope, sort_order, "
                "created_at, updated_at, version) VALUES (?, ?, ?, ?, ?, ?, ?, ?, 0)",
                (user_id, board["uid"], board["name"], board["year"], board["media_scope"],
                 order, board["created_at"] or ts, board["updated_at"] or ts),
            )
            board_id = int(cur.lastrowid)
            category_ids: dict[str, int] = {}
            for position, category in enumerate(board["categories"]):
                cur = conn.execute(
                    "INSERT INTO tier_categories (board_id, uid, label, rank_priority, "
                    "is_isolated, sort_order, colour, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                    (board_id, category["uid"], category["label"], category["rank_priority"],
                     int(category["is_isolated"]), position, category["colour"],
                     category["created_at"] or ts),
                )
                category_ids[category["uid"]] = int(cur.lastrowid)
            for item in board["items"]:
                category_uid = item["category_uid"]
                _insert_item(
                    conn, board_id, item["row"], item["added_from"],
                    item["created_at"] or ts,
                    category_id=None if category_uid is None else category_ids[category_uid],
                    rank=item["rank_in_category"],
                )
        return len(boards)

    return await db.transaction(_work)


def _validate_backup(doc: Any) -> list[dict[str, Any]]:
    """Read a backup document into the shape the restore writes, refusing
    anything it cannot fully account for.

    Caps are applied here exactly as they are on a live edit: a document is
    untrusted input like any other, and a file that would build a board no route
    could have built is a file this app should not accept.
    """
    if not isinstance(doc, Mapping):
        raise ValidationError("A backup must be a JSON object.")
    schema = doc.get("schema")
    if schema not in SUPPORTED_EXPORT_SCHEMAS:
        raise ValidationError(f"Unsupported rankings backup version: {schema!r}.")
    raw_boards = doc.get("boards") or []
    if not isinstance(raw_boards, list):
        raise ValidationError("`boards` must be a list.")
    if len(raw_boards) > MAX_BOARDS_PER_USER:
        raise ValidationError(f"A backup can hold at most {MAX_BOARDS_PER_USER} boards.")

    boards = [_validate_backup_board(entry) for entry in raw_boards]
    if len({board["uid"] for board in boards}) != len(boards):
        raise ValidationError("Two boards in this backup share an id.")
    per_year: dict[int, int] = {}
    for board in boards:
        if board["year"] is not None:
            per_year[board["year"]] = per_year.get(board["year"], 0) + 1
            if per_year[board["year"]] > MAX_BOARDS_PER_YEAR:
                raise ValidationError(
                    f"A backup can hold at most {MAX_BOARDS_PER_YEAR} boards for "
                    f"{board['year']}."
                )
    return boards


def _validate_backup_board(entry: Any) -> dict[str, Any]:
    if not isinstance(entry, Mapping):
        raise ValidationError("Each board must be an object.")
    raw_categories = entry.get("categories") or []
    raw_items = entry.get("items") or []
    if not isinstance(raw_categories, list) or not isinstance(raw_items, list):
        raise ValidationError("A board's categories and items must be lists.")
    if len(raw_categories) > MAX_CATEGORIES_PER_BOARD:
        raise ValidationError(f"A board holds at most {MAX_CATEGORIES_PER_BOARD} tiers.")
    if len(raw_items) > MAX_ITEMS_PER_BOARD:
        raise ValidationError(f"A board holds at most {MAX_ITEMS_PER_BOARD} titles.")

    categories = [_validate_backup_category(row) for row in raw_categories]
    uids = {category["uid"] for category in categories}
    if len(uids) != len(categories):
        raise ValidationError("Two tiers on one board share an id.")

    items = [_validate_backup_item(row, uids) for row in raw_items]
    keys = {item_key(item["row"]["media"], item["row"]["match_source"],
                     item["row"]["match_id"]) for item in items}
    if len(keys) != len(items):
        # The UNIQUE would drop the second copy silently, which would restore a
        # board that is quietly smaller than the one that was backed up.
        raise ValidationError("The same title appears twice on one board in this backup.")

    # Ordering is the artifact this feature produces, so it is carried across
    # rather than recomputed — but renumbered densely per tier on the way in, the
    # same normalization a layout save applies, so a hand-edited file cannot
    # introduce gaps or ties the rest of the app does not expect.
    items.sort(key=lambda item: item["rank_in_category"])
    ranks: dict[str | None, int] = {}
    for item in items:
        target = item["category_uid"]
        item["rank_in_category"] = 0 if target is None else ranks.get(target, 0)
        if target is not None:
            ranks[target] = item["rank_in_category"] + 1

    return {
        "uid": _uid(entry.get("uid"), "board"),
        "name": _name(entry.get("name"), MAX_BOARD_NAME, "board name"),
        "year": _year(entry.get("year")),
        "media_scope": _media_scope(entry.get("media_scope")),
        "created_at": _optional_int(entry.get("created_at")),
        "updated_at": _optional_int(entry.get("updated_at")),
        "categories": categories,
        "items": items,
    }


def _validate_backup_category(entry: Any) -> dict[str, Any]:
    if not isinstance(entry, Mapping):
        raise ValidationError("Each tier must be an object.")
    return {
        "uid": _uid(entry.get("uid"), "tier"),
        "label": _name(entry.get("label"), MAX_CATEGORY_LABEL, "tier label"),
        "rank_priority": _rank_priority(entry.get("rank_priority", 0)),
        "is_isolated": bool(entry.get("is_isolated")),
        "colour": _colour(entry.get("colour")),
        "created_at": _optional_int(entry.get("created_at")),
    }


def _validate_backup_item(entry: Any, category_uids: set[str]) -> dict[str, Any]:
    if not isinstance(entry, Mapping):
        raise ValidationError("Each title must be an object.")
    # _normalize_ref reads `ids`, while the export writes the stored `ids_json`
    # verbatim so a round trip is an identity. Parse it back into the map that
    # function expects rather than teaching it a second input shape.
    ref = dict(entry)
    if "ids" not in ref:
        ref["ids"] = _ids_from_json(entry.get("ids_json"))
    row = _normalize_ref(ref)

    category_uid = entry.get("category_uid")
    if category_uid is not None:
        category_uid = _uid(category_uid, "tier")
        if category_uid not in category_uids:
            # Silently pooling it would restore a board whose arrangement is
            # subtly different from the one that was saved, which is the one
            # thing a backup must not do.
            raise ValidationError(
                f"A title in this backup names tier {category_uid!r}, which is not on its board."
            )
    added_from = entry.get("added_from") or "manual"
    if added_from not in ADDED_FROM_VALUES:
        raise ValidationError(f"Unknown source {added_from!r}.")
    rank = _optional_int(entry.get("rank_in_category")) or 0
    if rank < 0:
        raise ValidationError("A rank cannot be negative.")
    return {
        "row": row,
        "category_uid": category_uid,
        "added_from": added_from,
        "rank_in_category": rank,
        "created_at": _optional_int(entry.get("created_at")),
    }


def _ids_from_json(value: Any) -> dict[str, Any]:
    """The provenance map out of a stored `ids_json` string. A map we can no
    longer read is dropped rather than refused: the row's own match_source and
    match_id are what the feature ranks by, and they are validated separately."""
    if not isinstance(value, str) or not value:
        return {}
    try:
        parsed = json.loads(value)
    except ValueError:
        return {}
    return parsed if isinstance(parsed, dict) else {}


def _touch(conn: db.Connection, board_id: int, user_id: int, ts: int) -> int:
    """Stamp a board as changed and bump the version a client echoes back.
    Returns the new version.

    Carries the ownership predicate even though the caller resolved the board
    already: every write in this module does, so no single missed check is enough
    to write across accounts.
    """
    conn.execute(
        "UPDATE tier_boards SET updated_at = ?, version = version + 1 "
        " WHERE id = ? AND user_id = ?",
        (ts, board_id, user_id),
    )
    return int(conn.execute(
        "SELECT version FROM tier_boards WHERE id = ?", (board_id,)
    ).fetchone()[0])
