def _resolve_board(conn: db.Connection, user_id: int, board_uid: str):
    """The caller's board row, or BoardNotFound. The ONLY way an integer board
    id is ever obtained."""
    row = conn.execute(
        "SELECT * FROM tier_boards WHERE user_id = ? AND uid = ?",
        (user_id, _uid(board_uid, "board")),
    ).fetchone()
    if row is None:
        raise BoardNotFound(f"No board {board_uid!r}.")
    return row


def _category_ids(conn: db.Connection, board_id: int) -> dict[str, int]:
    """uid -> id for every category on a board that has already been resolved to
    its owner, so these ids are owned by construction."""
    return {
        str(row["uid"]): int(row["id"])
        for row in conn.execute(
            "SELECT id, uid FROM tier_categories WHERE board_id = ?", (board_id,)
        )
    }


def _item_ids(conn: db.Connection, board_id: int) -> dict[str, int]:
    """Composite item key -> id, for one already-owned board."""
    return {
        item_key(row["media"], row["match_source"], row["match_id"]): int(row["id"])
        for row in conn.execute(
            "SELECT id, media, match_source, match_id FROM tier_items WHERE board_id = ?",
            (board_id,),
        )
    }


def _board_dict(row) -> dict[str, Any]:
    return {field: row[field] for field in _BOARD_FIELDS}


def _item_dict(row) -> dict[str, Any]:
    try:
        ids = json.loads(row["ids_json"])
    except ValueError:
        # A malformed map is provenance we can no longer read; it must not take
        # the board down with it, and the row's own match_source/match_id are
        # what the feature actually ranks by.
        ids = {}
    return {
        "key": item_key(row["media"], row["match_source"], row["match_id"]),
        "media": row["media"],
        "match_source": row["match_source"],
        "match_id": row["match_id"],
        "tmdb": row["tmdb"],
        "ids": ids if isinstance(ids, dict) else {},
        "title": row["title"],
        "year": row["year"],
        "network": row["network"],
        "season_count": row["season_count"],
        "episode_count": row["episode_count"],
        "runtime": row["runtime"],
        "user_rating": row["user_rating"],
        "added_from": row["added_from"],
        "rank_in_category": row["rank_in_category"],
    }


