async def add_titles(
    user_id: int,
    board_uid: str,
    refs: list[Mapping[str, Any]],
    *,
    added_from: str = "manual",
) -> int:
    """Add titles to a board's pool, returning how many were actually new.

    Idempotent by way of the board's UNIQUE constraint: re-adding a title that
    is already on the board — in the pool OR already tiered — does nothing,
    rather than duplicating it or dragging it back out of the tier it is in.

    `refs` are mappings carrying the item fields; the provider adapters that
    produce them convert their own value type into this shape, so nothing in
    this module knows which service a title came from.
    """
    if added_from not in ADDED_FROM_VALUES:
        raise ValidationError(f"Unknown source {added_from!r}.")
    rows = [_normalize_ref(ref) for ref in refs]
    ts = db.now()

    def _work(conn: db.Connection) -> int:
        board = _resolve_board(conn, user_id, board_uid)
        board_id = int(board["id"])
        existing = int(conn.execute(
            "SELECT COUNT(*) FROM tier_items WHERE board_id = ?", (board_id,)
        ).fetchone()[0])
        # Counted against the cap before inserting rather than after, so a
        # request that would overflow is refused whole rather than half applied.
        keys = {item_key(r["media"], r["match_source"], r["match_id"]) for r in rows}
        known = set(_item_ids(conn, board_id))
        if existing + len(keys - known) > MAX_ITEMS_PER_BOARD:
            raise ValidationError(f"A board holds at most {MAX_ITEMS_PER_BOARD} titles.")
        added = 0
        for row in rows:
            cur = conn.execute(
                "INSERT INTO tier_items (board_id, category_id, media, match_source, match_id, "
                "tmdb, ids_json, title, year, network, season_count, episode_count, runtime, "
                "user_rating, added_from, rank_in_category, created_at) "
                "VALUES (?, NULL, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0, ?) "
                "ON CONFLICT (board_id, media, match_source, match_id) DO NOTHING",
                (board_id, row["media"], row["match_source"], row["match_id"], row["tmdb"],
                 row["ids_json"], row["title"], row["year"], row["network"],
                 row["season_count"], row["episode_count"], row["runtime"],
                 row["user_rating"], added_from, ts),
            )
            added += cur.rowcount if cur.rowcount > 0 else 0
        if added:
            _touch(conn, board_id, user_id, ts)
        return added

    return await db.transaction(_work)


def _normalize_ref(ref: Mapping[str, Any]) -> dict[str, Any]:
    """Validate one incoming title into exactly the columns tier_items holds."""
    if not isinstance(ref, Mapping):
        raise ValidationError("Each title must be an object.")
    media = ref.get("media", "show")
    if media not in MEDIA_VALUES:
        raise ValidationError(f"Unknown media type {media!r}.")
    match_source = ref.get("match_source")
    if match_source not in MATCH_SOURCES:
        raise ValidationError(f"Unknown match source {match_source!r}.")
    match_id = str(ref.get("match_id") or "").strip()
    if not match_id:
        raise ValidationError("A title needs a match id.")
    ids = ref.get("ids") or {}
    if not isinstance(ids, Mapping):
        raise ValidationError("A title's ids must be an object.")
    return {
        "media": media,
        "match_source": match_source,
        "match_id": match_id,
        "tmdb": _optional_int(ref.get("tmdb")),
        # Unknown keys are omitted rather than stored as nulls, so the map stays
        # a record of what was actually known about this title.
        "ids_json": json.dumps({k: v for k, v in ids.items() if v not in (None, "")},
                               sort_keys=True),
        "title": _name(ref.get("title"), 300, "title"),
        "year": _optional_int(ref.get("year")),
        "network": _name(ref.get("network"), 120, "network"),
        "season_count": _optional_int(ref.get("season_count")),
        "episode_count": _optional_int(ref.get("episode_count")),
        "runtime": _optional_int(ref.get("runtime")),
        "user_rating": _optional_int(ref.get("user_rating")),
    }


def _optional_int(value: Any) -> int | None:
    if value is None or value == "":
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        raise ValidationError(f"Expected a whole number, got {value!r}.") from None


async def remove_items(user_id: int, board_uid: str, keys: list[Any]) -> int:
    """Delete titles from a board entirely — the only true delete in this
    module. Returns how many rows went.

    Every key is resolved against THIS board before anything is deleted, and one
    unresolvable key rejects the whole request: a partial delete driven by a
    payload we did not fully understand is worse than no delete at all.
    """
    parsed = [parse_item_key(key) for key in keys]

    def _work(conn: db.Connection) -> int:
        board = _resolve_board(conn, user_id, board_uid)
        board_id = int(board["id"])
        known = _item_ids(conn, board_id)
        ids = []
        for key in parsed:
            if str(key) not in known:
                raise ValidationError(f"No title {str(key)!r} on this board.")
            ids.append(known[str(key)])
        removed = 0
        for item_id in ids:
            cur = conn.execute(
                "DELETE FROM tier_items WHERE id = ? AND board_id = ?", (item_id, board_id)
            )
            removed += cur.rowcount
        if removed:
            _touch(conn, board_id, user_id, db.now())
        return removed

    return await db.transaction(_work)


