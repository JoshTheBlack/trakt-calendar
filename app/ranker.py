async def fetch_boards(user_id: int) -> list[dict[str, Any]]:
    """Every board this user owns, with its item count, newest grouping first.

    The count comes from one grouped join rather than a query per board — a user
    at the 50-board cap would otherwise cost 51 round trips to draw a switcher.
    """
    rows = await db.fetch_all(
        "SELECT b.*, COUNT(i.id) AS item_count "
        "  FROM tier_boards b LEFT JOIN tier_items i ON i.board_id = b.id "
        " WHERE b.user_id = ? "
        " GROUP BY b.id "
        " ORDER BY b.year IS NULL, b.year DESC, b.sort_order, b.id",
        (user_id,),
    )
    return [{**_board_dict(row), "item_count": int(row["item_count"])} for row in rows]


async def create_board(
    user_id: int,
    *,
    uid: str,
    name: str = "",
    year: int | None = None,
    media_scope: str = "mixed",
) -> dict[str, Any]:
    """Create an empty board. Raises ValidationError when a cap is reached."""
    board_uid = _uid(uid, "board")
    board_name = _name(name, MAX_BOARD_NAME, "board name")
    board_year = _year(year)
    scope = _media_scope(media_scope)
    ts = db.now()

    def _work(conn: db.Connection) -> dict[str, Any]:
        _check_board_caps(conn, user_id, board_year)
        if conn.execute(
            "SELECT 1 FROM tier_boards WHERE user_id = ? AND uid = ?", (user_id, board_uid)
        ).fetchone():
            raise ValidationError("That board already exists.")
        # Appended after whatever the user already has, so a new board does not
        # displace the ordering they arranged.
        next_order = int(conn.execute(
            "SELECT COALESCE(MAX(sort_order), -1) + 1 FROM tier_boards WHERE user_id = ?",
            (user_id,),
        ).fetchone()[0])
        conn.execute(
            "INSERT INTO tier_boards (user_id, uid, name, year, media_scope, sort_order, "
            "created_at, updated_at, version) VALUES (?, ?, ?, ?, ?, ?, ?, ?, 0)",
            (user_id, board_uid, board_name, board_year, scope, next_order, ts, ts),
        )
        return _board_dict(_resolve_board(conn, user_id, board_uid))

    return await db.transaction(_work)


def _check_board_caps(conn: db.Connection, user_id: int, year: int | None) -> None:
    """Both board caps, checked inside the write transaction so two concurrent
    creates cannot both find room for the same last slot."""
    total = int(conn.execute(
        "SELECT COUNT(*) FROM tier_boards WHERE user_id = ?", (user_id,)
    ).fetchone()[0])
    if total >= MAX_BOARDS_PER_USER:
        raise ValidationError(f"You can have at most {MAX_BOARDS_PER_USER} boards.")
    if year is not None:
        in_year = int(conn.execute(
            "SELECT COUNT(*) FROM tier_boards WHERE user_id = ? AND year = ?", (user_id, year)
        ).fetchone()[0])
        if in_year >= MAX_BOARDS_PER_YEAR:
            raise ValidationError(
                f"You can have at most {MAX_BOARDS_PER_YEAR} boards for {year}."
            )


async def update_board(
    user_id: int,
    board_uid: str,
    *,
    name: Any = None,
    year: Any = None,
    media_scope: Any = None,
) -> dict[str, Any]:
    """Rename a board and/or change its year or media scope.

    Each field is applied only when it was supplied, so a rename does not have to
    restate the year to avoid clearing it. Clearing the year is expressed by
    passing the empty string, which _year() reads as None — `None` here means
    "not part of this request" and cannot also mean "set it to nothing".
    """
    updates: dict[str, Any] = {}
    if name is not None:
        updates["name"] = _name(name, MAX_BOARD_NAME, "board name")
    if year is not None:
        updates["year"] = _year(year)
    if media_scope is not None:
        updates["media_scope"] = _media_scope(media_scope)

    def _work(conn: db.Connection) -> dict[str, Any]:
        board = _resolve_board(conn, user_id, board_uid)
        if updates:
            if "year" in updates and updates["year"] != board["year"]:
                _check_year_cap(conn, user_id, updates["year"])
            assignments = ", ".join(f"{column} = ?" for column in updates)
            conn.execute(
                f"UPDATE tier_boards SET {assignments}, updated_at = ? "
                " WHERE id = ? AND user_id = ?",
                (*updates.values(), db.now(), int(board["id"]), user_id),
            )
        return _board_dict(_resolve_board(conn, user_id, board_uid))

    return await db.transaction(_work)


def _check_year_cap(conn: db.Connection, user_id: int, year: int | None) -> None:
    """The per-year cap on its own, for a board moving INTO a year rather than
    being created in one."""
    if year is None:
        return
    in_year = int(conn.execute(
        "SELECT COUNT(*) FROM tier_boards WHERE user_id = ? AND year = ?", (user_id, year)
    ).fetchone()[0])
    if in_year >= MAX_BOARDS_PER_YEAR:
        raise ValidationError(f"You can have at most {MAX_BOARDS_PER_YEAR} boards for {year}.")


async def delete_board(user_id: int, board_uid: str) -> None:
    """Delete a board and, by cascade, its categories and items."""
    def _work(conn: db.Connection) -> None:
        board = _resolve_board(conn, user_id, board_uid)
        conn.execute(
            "DELETE FROM tier_boards WHERE id = ? AND user_id = ?", (int(board["id"]), user_id)
        )

    await db.transaction(_work)


async def clone_board(
    user_id: int, board_uid: str, *, uid: str, name: str = "",
) -> dict[str, Any]:
    """Copy a board, its tiers and everything in them onto a new uid.

    The copy is made entirely with INSERT...SELECT against ids that were resolved
    from the source board, so nothing crosses out of the caller's own data even
    if the source somehow held a stray reference.
    """
    new_uid = _uid(uid, "board")
    ts = db.now()

    def _work(conn: db.Connection) -> dict[str, Any]:
        source = _resolve_board(conn, user_id, board_uid)
        source_id = int(source["id"])
        new_name = _name(name, MAX_BOARD_NAME, "board name") or _clone_name(source["name"])
        _check_board_caps(conn, user_id, source["year"])
        if conn.execute(
            "SELECT 1 FROM tier_boards WHERE user_id = ? AND uid = ?", (user_id, new_uid)
        ).fetchone():
            raise ValidationError("That board already exists.")
        next_order = int(conn.execute(
            "SELECT COALESCE(MAX(sort_order), -1) + 1 FROM tier_boards WHERE user_id = ?",
            (user_id,),
        ).fetchone()[0])
        cur = conn.execute(
            "INSERT INTO tier_boards (user_id, uid, name, year, media_scope, sort_order, "
            "created_at, updated_at, version) VALUES (?, ?, ?, ?, ?, ?, ?, ?, 0)",
            (user_id, new_uid, new_name, source["year"], source["media_scope"],
             next_order, ts, ts),
        )
        new_id = int(cur.lastrowid)
        conn.execute(
            "INSERT INTO tier_categories (board_id, uid, label, rank_priority, is_isolated, "
            "sort_order, colour, created_at) "
            "SELECT ?, uid, label, rank_priority, is_isolated, sort_order, colour, ? "
            "  FROM tier_categories WHERE board_id = ?",
            (new_id, ts, source_id),
        )
        # Categories are matched back up by uid, which is unique per board and
        # was copied verbatim — so an item lands in the copy of the tier it was
        # in, with no id map to build in Python.
        conn.execute(
            "INSERT INTO tier_items (board_id, category_id, media, match_source, match_id, "
            "tmdb, ids_json, title, year, network, season_count, episode_count, runtime, "
            "user_rating, added_from, rank_in_category, created_at) "
            "SELECT ?, (SELECT c.id FROM tier_categories c "
            "             JOIN tier_categories o ON o.uid = c.uid "
            "            WHERE c.board_id = ? AND o.id = i.category_id), "
            "       i.media, i.match_source, i.match_id, i.tmdb, i.ids_json, i.title, i.year, "
            "       i.network, i.season_count, i.episode_count, i.runtime, i.user_rating, "
            "       i.added_from, i.rank_in_category, ? "
            "  FROM tier_items i WHERE i.board_id = ?",
            (new_id, new_id, ts, source_id),
        )
        return _board_dict(_resolve_board(conn, user_id, new_uid))

    return await db.transaction(_work)


def _clone_name(name: Any) -> str:
    """"Top 2026" -> "Top 2026 (copy)", trimmed back under the cap if the
    original was already near it."""
    base = (str(name) if name else "").strip() or "Untitled"
    suffix = " (copy)"
    return base[:MAX_BOARD_NAME - len(suffix)] + suffix


async def fetch_board(user_id: int, board_uid: str) -> dict[str, Any]:
    """One board with its categories, its tiered items and its pool.

    TWO queries for the contents regardless of how many tiers the board has —
    one for the categories, one for every item — grouped in Python afterwards.
    A query per category would make a 30-tier board 31 round trips to draw.
    """
    return await db.run(lambda conn: read_board(conn, user_id, board_uid))


def read_board(conn: db.Connection, user_id: int, board_uid: str) -> dict[str, Any]:
    """SYNCHRONOUS. The body of fetch_board, taking a connection so a caller
    already inside a transaction — a restore, say — can compose it rather than
    opening a second one."""
    board = _resolve_board(conn, user_id, board_uid)
    board_id = int(board["id"])
    categories = conn.execute(
        "SELECT * FROM tier_categories WHERE board_id = ? ORDER BY sort_order, id",
        (board_id,),
    ).fetchall()
    items = conn.execute(
        "SELECT * FROM tier_items WHERE board_id = ? ORDER BY rank_in_category, id",
        (board_id,),
    ).fetchall()

    by_category: dict[int, list[dict[str, Any]]] = {}
    pool: list[dict[str, Any]] = []
    for row in items:
        target = pool if row["category_id"] is None else \
            by_category.setdefault(int(row["category_id"]), [])
        target.append(_item_dict(row))

    return {
        **_board_dict(board),
        "categories": [
            {
                "uid": row["uid"],
                "label": row["label"],
                "rank_priority": row["rank_priority"],
                "is_isolated": bool(row["is_isolated"]),
                "sort_order": row["sort_order"],
                "colour": row["colour"],
                "items": by_category.get(int(row["id"]), []),
            }
            for row in categories
        ],
        "pool": pool,
    }


