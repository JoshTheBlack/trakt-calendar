def _uid(value: Any, what: str) -> str:
    if not isinstance(value, str) or not _UID.match(value):
        raise ValidationError(
            f"A {what} id must be 1-{MAX_UID_LENGTH} characters of letters, "
            "digits, hyphen or underscore."
        )
    return value


def _name(value: Any, limit: int, what: str) -> str:
    if value is None:
        return ""
    if not isinstance(value, str):
        raise ValidationError(f"A {what} must be text.")
    text = value.strip()
    if len(text) > limit:
        raise ValidationError(f"A {what} can be at most {limit} characters.")
    return text


def _year(value: Any) -> int | None:
    if value is None or value == "":
        return None
    try:
        year = int(value)
    except (TypeError, ValueError):
        raise ValidationError("Year must be a whole number.") from None
    # Wide enough for anything anyone would group a board by, narrow enough that
    # a stray timestamp pasted into the field is caught here rather than stored.
    if not 1870 <= year <= 2200:
        raise ValidationError("Year must be between 1870 and 2200.")
    return year


def _media_scope(value: Any) -> str:
    if value is None:
        return "mixed"
    if value not in MEDIA_SCOPES:
        raise ValidationError("Media scope must be one of: show, movie, mixed.")
    return str(value)


def _rank_priority(value: Any) -> int:
    try:
        priority = int(value)
    except (TypeError, ValueError):
        raise ValidationError("Rank priority must be a whole number.") from None
    if not 0 <= priority <= MAX_RANK_PRIORITY:
        raise ValidationError(f"Rank priority must be between 0 and {MAX_RANK_PRIORITY}.")
    return priority


def _colour(value: Any) -> str | None:
    if value is None or value == "":
        return None
    if not isinstance(value, str) or not _COLOUR.match(value):
        raise ValidationError("Colour must look like #RRGGBB.")
    return value.upper()


