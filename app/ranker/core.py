from typing import Any

from .. import db
# Re-exported deliberately (the same reasoning MEDIA_VALUES below carries): the
# identity a board row is keyed on is the app's notion of "the same title", not
# this feature's — the tracker files its own rows under the same triple. One
# definition, read from where it lives.
from ..providers.base import MATCH_SOURCES, ItemKey, Media, item_key  # noqa: F401
from ..providers.base import parse_item_key as base_parse_item_key

# Caps. Every one of these is enforced by rejecting the whole request, never by
# quietly truncating: a user who pasted a 90-character board name should be told
# it is too long, not shown a name they did not choose.
MAX_BOARD_NAME = 60
MAX_CATEGORY_LABEL = 40
MAX_RANK_PRIORITY = 1000
MAX_BOARDS_PER_USER = 50
MAX_BOARDS_PER_YEAR = 20
MAX_CATEGORIES_PER_BOARD = 30
# Far above the 100-item export ceiling on purpose: a board is a working set to
# curate down from, not just the finished list. This is also the number the
# pool's pagination and the poster warming are sized against.
MAX_ITEMS_PER_BOARD = 1000
MAX_UID_LENGTH = 64

# WHAT A BOARD REMEMBERS OF THE TITLES TAKEN OFF IT: the last twenty-five, for
# thirty days. Application constants rather than schema, so either can be tuned
# without a migration — `tier_item_removals` carries the column and the index both
# of them need. Twenty-five is "the last few things I removed, put that one back"
# with room to spare for an evening of pruning a pool; thirty days is long enough
# to notice a mistake after a weekend away and short enough that the history
# describes this month's board rather than last year's.
REMOVAL_HISTORY_PER_BOARD = 25
REMOVAL_HISTORY_DAYS = 30
REMOVAL_HISTORY_SECONDS = REMOVAL_HISTORY_DAYS * 24 * 60 * 60
# And of the TIERS deleted from it: the last ten, for the same thirty days. A
# board holds at most MAX_CATEGORIES_PER_BOARD tiers, so ten recent deletions is
# a third of the most any board could have — room for an evening of reorganizing
# without the list outgrowing the board it describes.
TIER_REMOVAL_HISTORY_PER_BOARD = 10

# Both derived from the app's one media vocabulary rather than restated. A scope
# is "one of the media kinds, or both at once", which is a statement ABOUT that
# set — so writing the members out again here would be a second copy that goes
# quietly stale rather than loudly wrong.
MEDIA_VALUES = frozenset(Media)
MEDIA_SCOPES = MEDIA_VALUES | {"mixed"}
ADDED_FROM_VALUES = frozenset({"manual", "tracker", "ratings"})

_COLOUR = re.compile(r"^#[0-9A-Fa-f]{6}$")
# A uid is generated by the client and then used as a database key and an HTML
# id, so it is held to an unambiguous alphabet rather than trusted.
_UID = re.compile(r"^[A-Za-z0-9_-]{1,%d}$" % MAX_UID_LENGTH)

# The columns a board row exposes outside this module, in the order the UI reads
# them. Listed once so fetch_boards and fetch_board cannot drift apart.
_BOARD_FIELDS = ("uid", "name", "year", "media_scope", "sort_order",
                 "created_at", "updated_at", "version")


class RankerError(Exception):
    """Base for the refusals this module raises. Each subclass maps to one HTTP
    status in the route layer, which is the only place that knows about HTTP."""


class BoardNotFound(RankerError):
    """No board with that uid belongs to this user.

    Deliberately the same answer for "no such board" and "somebody else's
    board": a caller who can tell those apart can enumerate other people's
    boards by uid, which is exactly the disclosure the uid addressing exists to
    prevent.
    """


class ValidationError(RankerError):
    """A payload broke a cap or a format rule. Nothing was written."""


class VersionConflict(RankerError):
    """The board changed since the client last read it — another tab saved
    first. The caller reloads rather than guessing which write wins."""


def parse_item_key(value: Any) -> ItemKey:
    """Parse the composite item key a client names a board item by.

    The parsing itself is shared (the tracker addresses its own rows the same
    way); what belongs to this module is that a bad key is a ValidationError, which
    the route layer already maps to a 400. Re-raising rather than letting a
    ValueError escape keeps that mapping in the one place that knows about HTTP.
    """
    try:
        return base_parse_item_key(value)
    except ValueError as exc:
        raise ValidationError(str(exc)) from None


